#!/usr/bin/env python3
"""Build the fonts embedded in report PDFs (OW-05 c8 / OW-12 c7).

The PDF's built-in Helvetica has no peso sign, so Export PDF embeds a subset of
Noto Sans (SIL Open Font License 1.1). This script

  1. subsets Noto Sans Regular and Bold to the characters the reports use
     (Latin, Latin-1, Latin Extended-A, punctuation, ₱, €, −) into
     assets/fonts/report-pdf/, and
  2. writes frontend/owner/reportPdfFonts.ts with, for each weight, the
     compressed font file and the metrics the PDF writer needs (character to
     glyph map, glyph widths, ascent, descent, cap height, bounding box).

Usage (needs fontTools: pip install fonttools):
  npm pack @expo-google-fonts/noto-sans   # in an empty folder, then extract it
  python3 scripts/build-report-pdf-fonts.py <NotoSans_400Regular.ttf> <NotoSans_700Bold.ttf>
"""
import base64
import json
import pathlib
import sys
import zlib

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / 'assets' / 'fonts' / 'report-pdf'
MODULE = ROOT / 'frontend' / 'owner' / 'reportPdfFonts.ts'
UNICODES = 'U+0020-007E,U+00A0-017F,U+2010-2027,U+2030,U+2039-203A,U+20AC,U+20B1,U+2122,U+2212'


def subset_font(source: pathlib.Path, target: pathlib.Path) -> None:
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True
    font = subset.load_font(str(source), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=subset.parse_unicodes(UNICODES))
    subsetter.subset(font)
    subset.save_font(font, str(target), options)


def describe(path: pathlib.Path, name: str) -> dict:
    data = path.read_bytes()
    font = TTFont(str(path))
    scale = 1000 / font['head'].unitsPerEm
    order = font.getGlyphOrder()
    gid = {glyph: index for index, glyph in enumerate(order)}
    hmtx = font['hmtx']
    head = font['head']
    os2 = font['OS/2']
    return {
        'name': name,
        'cmap': {str(code): gid[glyph] for code, glyph in sorted(font.getBestCmap().items())},
        'widths': [round(hmtx[glyph][0] * scale) for glyph in order],
        'ascent': round(os2.sTypoAscender * scale),
        'descent': round(os2.sTypoDescender * scale),
        'capHeight': round(getattr(os2, 'sCapHeight', 714) * scale),
        'bbox': [round(v * scale) for v in (head.xMin, head.yMin, head.xMax, head.yMax)],
        'length1': len(data),
        'file': base64.b64encode(zlib.compress(data, 9)).decode('ascii'),
    }


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    fonts = {}
    for key, source, name in (('regular', sys.argv[1], 'NotoSans-Regular'), ('bold', sys.argv[2], 'NotoSans-Bold')):
        target = FONT_DIR / f'{name}-subset.ttf'
        subset_font(pathlib.Path(source), target)
        fonts[key] = describe(target, name)
    MODULE.write_text(
        '// Generated by scripts/build-report-pdf-fonts.py — do not edit.\n'
        '// Noto Sans subsets (SIL Open Font License 1.1, see assets/fonts/report-pdf/OFL.txt)\n'
        '// embedded in report PDFs so that ₱ and other non-Latin-1 characters print.\n'
        'export type ReportPdfFont = {\n'
        '  name: string;\n'
        '  cmap: Record<string, number>;\n'
        '  widths: number[];\n'
        '  ascent: number;\n'
        '  descent: number;\n'
        '  capHeight: number;\n'
        '  bbox: [number, number, number, number];\n'
        '  /** Uncompressed size of the font file. */\n'
        '  length1: number;\n'
        '  /** The TrueType file, zlib-compressed, base64. */\n'
        '  file: string;\n'
        '};\n\n'
        f"export const REPORT_PDF_FONTS: {{ regular: ReportPdfFont; bold: ReportPdfFont }} = {json.dumps(fonts, separators=(',', ':'))};\n",
        encoding='utf-8',
    )
    print('wrote', MODULE.relative_to(ROOT), {key: (font['length1'], len(font['file'])) for key, font in fonts.items()})


if __name__ == '__main__':
    main()
